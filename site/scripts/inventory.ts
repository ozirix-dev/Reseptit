import { siteContent } from "../src/generated/content.generated";

const recipes = siteContent.recipes;
const locales = Object.fromEntries(["fi", "en", "sv", "th"].map((locale) => [locale, recipes.filter((r) => r.locale === locale).length]));
console.log(JSON.stringify({
  source: "Current local Markdown, regenerated by content:sync",
  locales,
  recipes: new Set(recipes.map((r) => r.recipeId)).size,
  publishedVersions: recipes.length,
  staticRoutes: recipes.length + Object.values(locales).filter(Boolean).length,
  images: new Set(recipes.flatMap((r) => r.image ? [r.image.src] : [])).size,
}, null, 2));
